import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {readFileSync} from 'node:fs';
import * as helpers from '../src/dispatch/planning-insights.mjs';
const require=createRequire(import.meta.url),ts=require('typescript'),React=require('react');
const {renderToStaticMarkup}=require('react-dom/server');
// Compile components in memory; no browser, build output or business-state mutation.
for(const ext of ['.ts','.tsx'])require.extensions[ext]=(module,filename)=>module._compile(ts.transpileModule(readFileSync(filename,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,jsx:ts.JsxEmit.ReactJSX,target:ts.ScriptTarget.ES2022}}).outputText,filename);
const {RouteChangesPanel}=require('../src/dispatch/components/RouteChanges.tsx');
let assertions=0;
const equal=(a,b)=>{assert.deepEqual(a,b);assertions++;};
const check=(value,message)=>{assert.ok(value,message);assertions++;};
const explanation={order_id:'O1',reason:'capacity',scope:'heuristic_candidate',summary:'EAST 容量不足',attempts:[],suggestions:[]};
const row={order_id:'O1',destination:'P27',priority:'urgent',status:'pending',earliest:0,deadline:1,expected:null,actual:null,deferred_reason:'capacity'};
const snapshot={id:'s',revision:1,traffic_version:0,now:0,running:false,ready:true,orders:[{id:'O1',destination:'P27',priority:'urgent',status:'pending'}],nodes:[{id:'P27',name:'游泳馆北侧配送点'}],vehicles:[],plan:{revision:0,traffic_version:0,fingerprint:'applied',deferred:[['O1','capacity']],accepted:[],routes:[],explanations:[explanation],report:{valid:true,safe_to_apply:true,complete_all:false}},planning_insights:{impact:null,timeline:{now:0,plan_revision:0,stale:false,stale_reason:null,orders:[row]},explanations:{source:'applied_plan',revision:0,traffic_version:0,stale:false,items:[explanation]}}};
const render=data=>renderToStaticMarkup(React.createElement(RouteChangesPanel,{data,changes:null,view:'after',setView:()=>{},busy:false,onPlan:()=>{},onVehicle:()=>{},onOrder:()=>{}}));
const initial=render(snapshot);
check(initial.includes('为什么未接纳 O1'),'first partial plan must expose refusal evidence without a route-diff baseline');
check(!initial.includes('先规划路线'),'an applied partial plan must not be presented as unplanned');
const sameSite=[row,{...row,order_id:'O2'}],before=JSON.stringify(sameSite);
equal(helpers.filterTimeline(sameSite,{query:'游泳馆',nodes:snapshot.nodes}).map(o=>o.order_id),['O1','O2']);
equal(helpers.filterTimeline(sameSite,{query:'P27',nodes:snapshot.nodes}).length,2);
equal(JSON.stringify(sameSite),before);

const response={error:{kind:'unsafe_plan',message:'protected cargo has no accepted continuation',report:{...snapshot.plan,revision:1,fingerprint:'candidate',report:{valid:false,safe_to_apply:false,complete_all:false},explanations:[{...explanation,summary:'本次失败提案证据'}]}}};
const bound=helpers.bindRejectedPlan(422,snapshot,response);
check(!!bound,'keep a matching actual rejected proposal');
equal(helpers.bindRejectedPlan(409,snapshot,response),null);
equal(helpers.bindRejectedPlan(422,snapshot,{error:{...response.error,kind:'invalid_input'}}),null);
equal(helpers.bindRejectedPlan(422,snapshot,{error:{...response.error,report:{...response.error.report,revision:0}}}),null);
equal(helpers.bindRejectedPlan(422,snapshot,{error:{...response.error,report:{...response.error.report,traffic_version:1}}}),null);
equal(helpers.bindRejectedPlan(422,snapshot,{error:{...response.error,report:{...response.error.report,report:{safe_to_apply:true}}}}),null);
equal(helpers.retainRejectedPlan(bound,{...snapshot}),bound);
equal(helpers.retainRejectedPlan(bound,{...snapshot,id:'other'}),null);
equal(helpers.retainRejectedPlan(bound,{...snapshot,revision:2}),null);
equal(helpers.retainRejectedPlan(bound,{...snapshot,traffic_version:1}),null);
equal(helpers.retainRejectedPlan(bound,null),null);
const source=JSON.stringify(snapshot),view=helpers.withRejectedPlan(snapshot,bound);
equal(view.plan,snapshot.plan);
equal(view.planning_insights,snapshot.planning_insights);
equal(JSON.stringify(snapshot),source);
equal(helpers.explanationFor(view,'O1').summary,'本次失败提案证据');
check(render(view).includes('失败提案，未应用'),'a 422 proposal cannot masquerade as an applied plan');
equal(helpers.withRejectedPlan({...snapshot,revision:2},bound).rejected_proposal,undefined);
equal(helpers.explanationFor({...snapshot,rejected_proposal:{...bound,session_id:'other'}},'O1').summary,'EAST 容量不足');
const refreshed=render({...snapshot,planning_insights:{...snapshot.planning_insights,explanations:{...snapshot.planning_insights.explanations,stale:true}}});
check(refreshed.includes('上次尝试'),'stale rejection remains clearly historical after a refresh');
console.log(`${assertions} first-plan, destination-name and rejected-response binding assertions passed`);
