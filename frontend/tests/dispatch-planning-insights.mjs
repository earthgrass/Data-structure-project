import assert from 'node:assert/strict';
import {signedDifference,timePosition,timelineDomain,filterTimeline,explanationFor} from '../src/dispatch/planning-insights.mjs';

let count=0;
const equal=(a,b)=>{assert.deepEqual(a,b);count++;};
equal(signedDifference(2),'增加 2.00');
equal(signedDifference(-2),'减少 2.00');
equal(signedDifference(0),'不变');
equal(signedDifference(null),'暂无对照');
equal(signedDifference(NaN),'暂无对照');
equal(signedDifference(.001),'增加 <0.01');
equal(signedDifference(-.001),'减少 <0.01');
equal(timePosition(5,{start:0,end:10}),50);
equal(timePosition(null,{start:0,end:10}),null);
equal(timePosition(NaN,{start:0,end:10}),null);
equal(timePosition(-1,{start:0,end:10}),0);
equal(timePosition(20,{start:0,end:10}),100);
equal(timePosition(0,{start:0,end:0}),0);
const base={order_id:'O1',destination:'P1',priority:'normal',status:'planned',earliest:2,deadline:12,expected:{vehicle:'EAST',arrival:3,service_start:4,signoff:5,slack:7},actual:null};
const rows=[base,{...base,order_id:'O2',status:'delivered',actual:{vehicle:'EAST',arrival:4,service_start:6,signoff:8,slack:4}},{...base,order_id:'O3',status:'pending',expected:null},{...base,order_id:'O4',status:'cancelled',expected:null},{...base,order_id:'O5',expected:{vehicle:'EAST',arrival:4,service_start:7,signoff:12,slack:0}}];
const original=JSON.stringify(rows);
equal(timelineDomain([],0),{start:0,end:1});
equal(timelineDomain(rows,3),{start:2,end:12});
equal(timelineDomain(rows,20),{start:2,end:20});
equal(filterTimeline(rows,{query:'O1'}).map(x=>x.order_id),['O1']);
equal(filterTimeline(rows,{query:'east'}).map(x=>x.order_id),['O1','O2','O5']);
equal(filterTimeline(rows,{activeOnly:true}).map(x=>x.order_id),['O1','O3','O5']);
equal(filterTimeline(rows,{riskOnly:true,threshold:5}).map(x=>x.order_id),['O5']);
equal(filterTimeline(rows,{riskOnly:true,threshold:7}).map(x=>x.order_id),['O1','O5']);
equal(filterTimeline(rows,{riskOnly:true,threshold:0}).map(x=>x.order_id),['O5']);
equal(filterTimeline(rows,{query:'none'}),[]);
equal(filterTimeline(rows,{riskOnly:true,threshold:5,forecastCurrent:false}),[]);
equal(filterTimeline([{...base,expected:{...base.expected,slack:NaN}}],{riskOnly:true}),[]);
equal(JSON.stringify(rows),original);
const e={order_id:'O3',reason:'capacity',attempts:[{load:'0.30000000000000000001',capacity:'0.3'}]};
equal(explanationFor({plan:{explanations:[e]}},'O3'),e);
equal(explanationFor({plan:{explanations:[e]}},'missing'),null);
equal(explanationFor({},'O3'),null);
equal(explanationFor({plan:{explanations:[e]},planning_insights:{explanations:{items:[]}}},'O3'),null);
equal(explanationFor({planning_insights:{explanations:{items:[e]}}},'O3').attempts[0].load,'0.30000000000000000001');
console.log(`${count} planning insight formatting, timeline filtering and exact evidence assertions passed`);
