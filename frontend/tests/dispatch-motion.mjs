import assert from 'node:assert/strict';
import {driveFraction,vehiclePoint,segmentDuration,physicalRoads} from '../src/dispatch/motion.mjs';
const action={kind:'drive',source:'A',target:'B',start:10,end:30};
assert.equal(driveFraction(action,5),0);
assert.equal(driveFraction(action,20),.5);
assert.equal(driveFraction(action,35),1);
assert.equal(driveFraction({...action,end:10},10),0);
const points=new Map([['A',[10,20]],['B',[110,220]]]);
const car={position:'A',current:action};
assert.deepEqual(vehiclePoint(car,20,points),[60,120]);
assert.equal(car.position,'A');
assert.deepEqual(vehiclePoint({...car,current:{...action,kind:'load'}},20,points),[10,20]);
assert.deepEqual(vehiclePoint({...car,current:{...action,source:'missing'}},20,points),[10,20]);
assert.equal(segmentDuration(0,100,2),segmentDuration(0,100,1)/2);
assert.equal(segmentDuration(0,100,1,true),0);
const roads=physicalRoads([{source:'A',target:'B',cost:10},{source:'B',target:'A',cost:12},{source:'B',target:'C',cost:2}]);
assert.equal(roads.length,2);assert.equal(roads[0].directions.length,2);
assert.deepEqual(roads[0].directions.map(e=>e.cost),[10,12]);
assert.equal(roads[1].directions.length,1);
console.log('14 motion, timing, immutable position and physical-road assertions passed');
